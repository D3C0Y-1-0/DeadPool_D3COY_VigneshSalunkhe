@app.route("/")
def index():
    return redirect("/login")

@app.route("/login", methods=["GET", "POST"])
def login():
    err = None
    if request.method == "POST":
        u = request.form.get("u", "")[:128]
        p = request.form.get("p", "")[:128]
        flags = []
        if SQLI.search(u + " " + p):
            flags.append("sqli")
        if TRAV.search(u + " " + p):
            flags.append("traversal")

        ok = (u, p) in {("admin", "admin"), ("admin", "Welcome1")}
        log_event(action="login", user=u, password=p, outcome="success" if ok else "failure", flags=flags, path="/login")

        if ok:
            resp = make_response(redirect("/dashboard"))
            resp.set_cookie("sid", "demo-session-token", httponly=True)
            return resp
        err = "Invalid corporate credentials."

    return render_template_string(PAGE, err=err)

@app.route("/dashboard")
def dashboard():
    log_event(action="web_request", path="/dashboard", outcome="allow")
    return render_template_string(DASH)

@app.route("/download/customer_data_2026.csv")
def download_csv():
    data = csv_bytes()
    sha256 = hashlib.sha256(data).hexdigest()
    log_event(
        action="download",
        path=request.path,
        honeytoken_id="HT-CUST-001",
        file={"name": "customer_data_2026.csv", "size": len(data), "sha256": sha256},
        outcome="success"
    )
    return Response(
        data,
        mimetype="text/csv",
        headers={"Content-Disposition": "attachment; filename=customer_data_2026.csv"}
    )

@app.route("/robots.txt")
def robots():
    return Response("User-agent: *\nDisallow: /admin-backup/\n", mimetype="text/plain")

@app.route("/admin-backup/")
def admin_backup():
    log_event(action="web_request", path=request.path, flags=["lure_path"], outcome="drop")
    return Response("403 Forbidden - Access Restricted to Internal Auditors\n", status=403, mimetype="text/plain")

@app.after_request
def trace_request(resp):
    if request.path not in ("/login", "/dashboard", "/admin-backup/") and not request.path.startswith("/download"):
        flags = []
        if TRAV.search(request.full_path):
            flags.append("traversal")
        log_event(action="web_request", path=request.full_path, status=resp.status_code, flags=flags)
    return resp

